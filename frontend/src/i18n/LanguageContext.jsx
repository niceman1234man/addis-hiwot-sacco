function translateText(text, language) {
  if (language === "en" || !text.trim()) return text;
  const trimmed = text.trim();
  const exactTranslation = translations[trimmed];
  if (exactTranslation) return text.replace(trimmed, exactTranslation);
  let translated = text;
  for (const [source, target] of Object.entries(translations).sort((a, b) => b[0].length - a[0].length)) {
    if (source.length > 4 && translated.includes(source)) translated = translated.replaceAll(source, target);
  }
  for (const [source, target] of Object.entries(wordTranslations).sort((a, b) => b[0].length - a[0].length)) {
    if (trimmed.toLowerCase() === source.toLowerCase()) return text.replace(trimmed, target);
  }
  return translated;
}

function applyLanguage(root, language, textRecords, attributeRecords) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!node.nodeValue?.trim() || node.parentElement?.closest("script, style, textarea, input, [data-no-translate]")) continue;
    let record = textRecords.get(node);
    if (!record) {
      record = { original: node.nodeValue, translated: "" };
      textRecords.set(node, record);
    } else if (node.nodeValue !== record.translated) {
      record.original = node.nodeValue;
    }
    const next = language === "am" ? translateText(record.original, language) : record.original;
    if (node.nodeValue !== next) {
      record.translated = next;
      node.nodeValue = next;
    } else record.translated = next;
  }

  const elements = root.querySelectorAll("[placeholder], [title], [aria-label]");
  for (const element of elements) {
    for (const attribute of ["placeholder", "title", "aria-label"]) {
      if (!element.hasAttribute(attribute)) continue;
      let records = attributeRecords.get(element);
      if (!records) {
        records = new Map();
        attributeRecords.set(element, records);
      }
      let record = records.get(attribute);
      const current = element.getAttribute(attribute);
      if (!record) {
        record = { original: current, translated: "" };
        records.set(attribute, record);
      } else if (current !== record.translated) record.original = current;
      const next = language === "am" ? translateText(record.original, language).trim() : record.original;
      if (current !== next) {
        record.translated = next;
        element.setAttribute(attribute, next);
      } else record.translated = next;
    }
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem(STORAGE_KEY) === "am" ? "am" : "en");
  const textRecords = useMemo(() => new WeakMap(), []);
  const attributeRecords = useMemo(() => new WeakMap(), []);

  useEffect(() => {
    const root = document.body;
    document.documentElement.lang = language === "am" ? "am" : "en";
    localStorage.setItem(STORAGE_KEY, language);
    document.title = language === "am" ? "አዲስ ሕይወት ቁጠባና ብድር ህብረት ስራ ማህበር" : "Addis Hiwot SACCO";
    applyLanguage(root, language, textRecords, attributeRecords);
    const observer = new MutationObserver(() => applyLanguage(root, language, textRecords, attributeRecords));
    observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["placeholder", "title", "aria-label"] });
    return () => observer.disconnect();
  }, [language, textRecords, attributeRecords]);

  const value = useMemo(() => ({ language, setLanguage, toggleLanguage: () => setLanguage((current) => current === "en" ? "am" : "en") }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider.");
  return context;
}

export function LanguageToggle({ className = "" }) {
  const { language, toggleLanguage } = useLanguage();
  return <button className={`language-toggle ${className}`.trim()} type="button" onClick={toggleLanguage} aria-label={language === "en" ? "Switch language to Amharic" : "ቋንቋን ወደ እንግሊዝኛ ቀይር"} title={language === "en" ? "Switch to Amharic" : "ወደ እንግሊዝኛ ቀይር"}>
    {language === "en" ? "አማ" : "EN"}
  </button>;
}
